def demo_brief(scenario_id, spec):
    brief = _base_demo_brief(scenario_id, spec)
    detail = DETAILS[scenario_id]
    for section in brief['sections']:
        role = section['role']
        if role == 'context': section['body'] = detail['body']
        if role == 'solution':
            for card, desc in zip(section['cards'], detail['descs']): card['desc'] = desc
        if role == 'evidence':
            section['metrics'] = [dict(value=value,label=label,delta='演示数据') for value,label in detail['metrics']]
        if role == 'comparison' and 'table' in detail: section['table'] = deepcopy(detail['table'])
        if role == 'process' and 'steps' in detail:
            for card, desc in zip(section['cards'], detail['steps']): card['desc'] = desc
        if role == 'business' and 'business' in detail:
            section['body'] = detail['business']; section['bullets'] = detail['business_points']
        if role == 'closing': section['body'] = detail['closing']
    return brief
